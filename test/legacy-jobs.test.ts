import assert from 'node:assert/strict';
import { cp, readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import test from 'node:test';
import { z } from 'zod';
import { createFilmGraph, runFilm, type CommandRunner } from '../harness/graph/film-graph.js';
import { packageRoot } from '../harness/runtime/paths.js';
import { compositionFingerprint } from '../harness/worker/fingerprint.js';
import { readJobStatus } from '../web/job-state.js';
import {
  audioCatalogSchema, checkResultSchema, checkedCompositionSchema, graphEventSchema, graphReportSchema, planDataSchema, planGateSchema,
  renderHandoffSchema, renderReportSchema, sourceManifestSchema, webJobSchema, type FilmInput,
} from '../shared/film.js';
import { readJsonWith, readJson, parseJsonLines } from '../shared/json.js';
import { defined, withTempDir } from './helpers.js';

/*
 * These fixtures were generated by the pre-migration JavaScript build. They prove the TypeScript build
 * reads (and resumes) jobs it did not write, without changing their on-disk format.
 */
const FIXTURES = join(packageRoot(), 'test', 'fixtures', 'legacy-jobs');
const FAILED = '11111111-1111-4111-8111-111111111111';
const COMPLETE = '22222222-2222-4222-8222-222222222222';

async function copyFixtures(into: string): Promise<void> {
  await cp(FIXTURES, into, { recursive: true });
}

test('jobs saved by the JavaScript build are listed with their original status', async () => {
  await withTempDir('youiagent-legacy-', async (jobs) => {
    await copyFixtures(jobs);
    const failed = defined(await readJobStatus(join(jobs, FAILED), false));
    assert.equal(failed.state, 'failed');
    assert.deepEqual(failed.resume, { eligible: true, source: true, plan: true, composition: true, from: 'composition check' });
    assert.equal(failed.filmReady, false);
    assert.match(failed.error ?? '', /Render worker failed/);
    assert.equal(failed.phases.composition, true);
    const complete = defined(await readJobStatus(join(jobs, COMPLETE), false));
    assert.equal(complete.state, 'complete');
    assert.equal(complete.filmReady, true);
    assert.equal(complete.render?.hasAudio, true);
    assert.equal(complete.render?.durationSeconds, 18);
    assert.equal(complete.resume.eligible, false);
  });
});

test('every persisted file in a legacy job parses against the current schemas', async () => {
  for (const id of [FAILED, COMPLETE]) {
    const job = join(FIXTURES, id);
    await readJsonWith(join(job, 'web-job.json'), webJobSchema);
    await readJsonWith(join(job, 'source-manifest.json'), sourceManifestSchema);
    await readJsonWith(join(job, 'plan-gate.json'), planGateSchema);
    await readJsonWith(join(job, 'check-result.json'), checkResultSchema);
    await readJsonWith(join(job, 'checked-composition.json'), checkedCompositionSchema);
    const workspace = join(job, 'workspace');
    await readJsonWith(join(workspace, 'film-output', 'plan-data.json'), planDataSchema);
    await readJsonWith(join(workspace, 'film-output', 'render-handoff.json'), renderHandoffSchema);
    await readJsonWith(join(workspace, 'film-audio', 'catalog.json'), audioCatalogSchema);
    const events = parseJsonLines(await readFile(join(job, 'graph-events.jsonl'), 'utf8'), graphEventSchema);
    assert.ok(events.length > 4, 'events should survive parsing');
  }
  const done = join(FIXTURES, COMPLETE);
  await readJsonWith(join(done, 'graph-report.json'), graphReportSchema);
  await readJsonWith(join(done, 'workspace', 'film-output', 'render-report.json'), renderReportSchema);
});

test('the composition fingerprint matches the one the JavaScript build recorded', async () => {
  const attestation = await readJsonWith(join(FIXTURES, FAILED, 'checked-composition.json'), checkedCompositionSchema);
  const composition = join(FIXTURES, FAILED, 'workspace', 'film-output', 'composition');
  assert.equal(await compositionFingerprint(composition), attestation.sha256, 'a changed hash would force every saved film to re-check');
});

test('a failed legacy job resumes from its checkpoints without rewriting them', async () => {
  await withTempDir('youiagent-legacy-resume-', async (jobs) => {
    await copyFixtures(jobs);
    const jobDir = join(jobs, FAILED);
    const untouched = ['source-manifest.json', 'plan-gate.json', 'web-job.json', join('workspace', 'film-output', 'plan-data.json'), join('workspace', 'film-output', 'film-plan.md'), join('workspace', 'film-output', 'composition', 'index.html'), join('workspace', 'film-output', 'render-handoff.json'), join('workspace', 'source-repo', 'README.md')];
    const before = await Promise.all(untouched.map((name) => readFile(join(jobDir, name))));

    const saved = z.looseObject({ websiteUrl: z.string(), repositoryUrl: z.string(), goal: z.string() }).parse(await readJson(join(jobDir, 'graph-input.json')));
    const input: FilmInput = { websiteUrl: saved.websiteUrl, repositoryUrl: saved.repositoryUrl, goal: saved.goal, audioDir: null, musicMode: 'silent', provider: 'codex', model: 'fixture', effort: 'high', resumePlan: true, resumeComposition: true };

    const agentStages: string[] = [];
    let evaluations = 0;
    let checks = 0;
    const run: CommandRunner = async (_name, _args, cwd) => {
      if (cwd.endsWith('composition')) { checks++; return { code: 0, output: '{"ok":true}', error: '' }; }
      const { writeFile } = await import('node:fs/promises');
      await writeFile(join(cwd, 'film-output', 'film.mp4'), 'fixture');
      await writeFile(join(cwd, 'film-output', 'render-report.json'), JSON.stringify({ output: 'film-output/film.mp4', durationSeconds: 18, hasAudio: true }));
      return { code: 0, output: '', error: '' };
    };
    const graph = createFilmGraph({
      prep: async () => {},
      capture: async () => { throw new Error('a resumed job must not capture its source again'); },
      agent: async (_workspace, _job, stage) => { agentStages.push(stage); },
      evaluator: async () => { evaluations++; return { probabilitySupported: 1 }; },
      run,
      review: async () => ({ status: 'reported', report: 'fixture' }),
    });

    const { result } = await runFilm(input, { jobDir, graph });

    assert.deepEqual(agentStages, [], 'planning and composition are reused, not regenerated');
    assert.equal(evaluations, 0, 'the saved claim decision is reused, which proves the plan cache key is compatible');
    assert.equal(checks, 1, 'the saved composition is re-checked');
    assert.equal(result.render?.durationSeconds, 18);
    const after = await Promise.all(untouched.map((name) => readFile(join(jobDir, name))));
    untouched.forEach((name, index) => assert.ok(defined(before[index]).equals(defined(after[index])), `${name} must not be rewritten by a resume`));
    const events = parseJsonLines(await readFile(join(jobDir, 'graph-events.jsonl'), 'utf8'), graphEventSchema);
    assert.equal(events.at(-1)?.node, 'review');
    assert.ok((await readdir(jobDir)).includes('graph-report.json'));
  });
});
